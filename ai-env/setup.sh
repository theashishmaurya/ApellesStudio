#!/usr/bin/env bash
# Create or repair the ONE virtual environment both Apelles Python sidecars run
# from (D-314). `ai/` and `ai-media/` stay two separate processes; they just stop
# duplicating ~1.1 GB of identical torch/opencv/numpy/scipy wheels.
#
#   ./ai-env/setup.sh                install .venv from requirements.lock.txt
#   ./ai-env/setup.sh --relock       re-resolve BOTH sidecar requirement files
#                                    into a fresh .venv and rewrite
#                                    requirements.lock.txt
#   ./ai-env/setup.sh --fetch-models one-time, EXPLICIT download of
#                                    ai-media/video_understand.py's VLM weights
#                                    (network on for this step only) — B-172/D-354
#
# What it does NOT do: install ffmpeg (a hard requirement of ai-media/, not
# pip-installable). Most models pull from the HF cache on first use; the one
# exception is understand_video's Qwen3-VL, whose subprocess runs fully
# offline always (D-354's local-first call) and so must be fetched explicitly
# via --fetch-models — see ai-media/video_understand.py and docs/BUGS.md B-172.
# See ai-env/README.md.
set -euo pipefail

cd "$(dirname "$0")"
HERE="$PWD"
ROOT="$(cd .. && pwd)"
VENV="$HERE/.venv"
LOCK="$HERE/requirements.lock.txt"
PY="${PYTHON:-python3}"

RELOCK=0
FETCH_MODELS=0
case "${1:-}" in
  --relock) RELOCK=1 ;;
  --fetch-models) FETCH_MODELS=1 ;;
  "") ;;
  *) echo "usage: $0 [--relock|--fetch-models]" >&2; exit 2 ;;
esac

if [ "$FETCH_MODELS" = 1 ]; then
  # B-172/D-354 — the one explicit, one-time step that populates the HF cache
  # for understand_video's VLM. Deliberately its own early-exit branch: this
  # does not touch the venv build/relock flow above or below it, it just needs
  # that venv (and its huggingface_hub) to already exist.
  if [ ! -x "$VENV/bin/python" ]; then
    echo "error: no $VENV yet — run '$0' first to create it, then retry --fetch-models" >&2
    exit 1
  fi
  echo "==> fetching understand_video's model (one-time, ~2.9 GB; network on for"
  echo "    this step only — every real call after this stays HF_HUB_OFFLINE=1)"
  env -u HF_HUB_OFFLINE "$VENV/bin/python" -c "
import sys
sys.path.insert(0, '$ROOT/ai-media')
from huggingface_hub import snapshot_download
from video_understand import MODEL
print(f'downloading {MODEL} into the HF cache ...')
snapshot_download(MODEL)
print('done — understand_video will now run fully offline.')
"
  exit 0
fi

# The two sidecars' own requirement files are the human-edited source of truth
# and the input to --relock. Resolving them in ONE pip invocation is the point:
# that is what makes pip reconcile both sidecars' constraints against each other
# instead of letting the second install silently move what the first one pinned
# — the exact failure D-314's own history records.
IN_FILES=("$ROOT/ai/requirements.txt" "$ROOT/ai-media/requirements.txt")
for f in "${IN_FILES[@]}"; do
  [ -f "$f" ] || { echo "error: missing $f" >&2; exit 1; }
done

if [ "$RELOCK" = 1 ]; then
  echo "==> --relock: rebuilding $VENV from scratch"
  # From scratch deliberately. Re-resolving on top of an existing environment
  # would let a package that is no longer required by anything survive into the
  # freeze below, and the lock would then carry dependencies nothing asks for.
  rm -rf "$VENV"
fi

if [ ! -x "$VENV/bin/python" ]; then
  echo "==> creating $VENV ($("$PY" -V 2>&1))"
  "$PY" -m venv "$VENV"
fi
"$VENV/bin/python" -m pip install --quiet --upgrade pip

if [ "$RELOCK" = 1 ]; then
  echo "==> resolving ai/ + ai-media/ together"
  "$VENV/bin/pip" install -r "${IN_FILES[0]}" -r "${IN_FILES[1]}"

  echo "==> writing $LOCK"
  {
    echo "# GENERATED by ai-env/setup.sh --relock — do not hand-edit (D-314)."
    echo "#"
    echo "# The full transitive closure of ai/requirements.txt + ai-media/requirements.txt"
    echo "# resolved TOGETHER, which is what both sidecars' one shared venv is built"
    echo "# from. Pinning the transitives — not just the direct deps — is the actual"
    echo "# guard against this stack's known failure mode: a transitive (transformers,"
    echo "# tokenizers, numpy, mlx-metal) getting moved out from under a sidecar by an"
    echo "# unrelated install. Edit the two sidecar files, then re-run --relock."
    echo "#"
    echo "# Python $("$VENV/bin/python" -c 'import sys; print(".".join(map(str, sys.version_info[:3])))'), macOS arm64."
    "$VENV/bin/pip" freeze
  } > "$LOCK"
else
  [ -f "$LOCK" ] || { echo "error: no $LOCK — run: $0 --relock" >&2; exit 1; }
  echo "==> installing from $LOCK"
  "$VENV/bin/pip" install -r "$LOCK"
fi

# Prove the environment actually serves both sidecars, rather than reporting
# success on "pip exited 0". The check list lives in `verify.py` rather than
# inline here (D-315): the Rust bootstrap in `apelles_ai::ai_env` runs the exact
# same file on every app launch to decide whether the venv it found is usable or
# has to be wiped and rebuilt, and two hand-maintained copies of that list — one
# in bash, one in Rust — would drift into "the app says healthy, the sidecar dies
# on import."
echo "==> verifying both sidecars' key imports"
"$VENV/bin/python" "$HERE/verify.py"

# A leftover per-sidecar venv silently wins over this one (the interpreter ladder
# in apelles_ai::sidecar prefers the more specific path on purpose), so an install
# that looks done would keep running on the old 1.6-1.9 GB environments. Say so
# rather than leaving it to be discovered.
STALE=()
for d in ai ai-media; do
  [ -e "$ROOT/$d/.venv" ] && STALE+=("$d/.venv")
done
if [ ${#STALE[@]} -gt 0 ]; then
  echo
  echo "note: the pre-D-314 per-sidecar venv(s) ${STALE[*]} still exist, and the app"
  echo "      prefers them over this shared one. They are no longer needed — remove"
  echo "      them to reclaim the disk:"
  for s in "${STALE[@]}"; do echo "        rm -rf $ROOT/$s"; done
fi

echo
echo "==> done: $VENV"
echo "    both sidecars will use it automatically — no env vars needed."
